#ifndef __FUNCTION_H
#define __FUNCTION_H

/*
 * ============================================================
 * 麦轮底盘执行器层
 *
 * 【职责】
 *   1. 麦轮逆运动学: 把 (vx, vy, omega) 拆成四个轮子的 (方向, 转速)
 *   2. 驱动器协议: 把命令打包成 Emm_V5 帧
 *   3. 发送调度:  统一走 DMA + 环形队列, 主循环永不阻塞
 *
 * 【电机编号】(与实物对应, 不要随意改)
 *            车头
 *      3(左前)      1(右前)
 *      4(左后)      2(右后)
 *
 *   左侧两个轮子是反向安装的, 由 function.c 里的 MOTOR_3/4_DIR_INVERT
 *   单轮翻转。这张表是实测出来的, 改动必须重新标定惯导路径。
 *
 * 【为什么发送要进队列】
 *   原来速度帧走 DMA、停止帧走阻塞 HAL_UART_Transmit, 两者共用
 *   huart1.gState: 只要发停止帧的那一刻上一次 DMA 还没结束,
 *   HAL 就直接返回 HAL_BUSY, 那一帧**一个字节都不发**。
 *   现在所有帧统一进一个环形队列, 由 Car_TxTask() 用 DMA 逐帧发出,
 *   既不会出现 HAL_BUSY, 也不会阻塞主循环。
 * ============================================================
 */

#include <stdint.h>

/* 底盘电机个数 */
#define CAR_MOTOR_NUM       4u

/* ---------------- 常用动作(内部都是 Car_Mecanum) ---------------- */

/* 【核心】麦轮逆运动学, 三个分量任意叠加:
 *   vx    : 前进速度(RPM), 正数前进, 负数后退
 *   vy    : 左移速度(RPM), 正数左移, 负数右移
 *   omega : 自转速度(RPM), 正数逆时针(原地左转), 负数顺时针
 *
 * 例: Car_Mecanum(50,  0,  0)  直行
 *     Car_Mecanum( 0, 50,  0)  原地左移
 *     Car_Mecanum( 0, 50,  4)  边左移边往左修航向
 *     Car_Mecanum( 0,  0, 30)  原地左转
 *
 * 只负责把 5 帧命令塞进发送队列, 立即返回。 */
void Car_Mecanum(int16_t vx, int16_t vy, int16_t omega);

/* 【停车】四个电机全部"立即停止"。
 *
 * 内部对每台各发两帧 snF=0 的立即停止帧, **不发广播同步帧**:
 * 缓存式停止(snF=1)要求驱动器先收到自己那帧、再收到同步帧;
 * 任意一帧在驱动器侧丢失, 它的缓存里就还是上一拍的速度命令,
 * 再来的同步帧会把那条旧速度**重新执行** —— 那个轮子就被"唤醒"了。
 * 立即停止帧收到即停, 完全不依赖后续帧。
 *
 * 只塞队列, 立即返回。真正的"停住没有"要等队列排空后靠编码器确认。 */
void Car_Stop(void);

/* 【单轮补停】只停一台, 发两帧立即停止帧。停车确认发现哪台还在转就用它。 */
void Car_StopMotor(uint8_t motor_id);

/* 【使能/失能】四台一起发, 返回 1 表示全部入队成功。 */
uint8_t Car_SetEnabled(uint8_t enabled);

/* 【读位置】读某台的 S_CPOS 脉冲计数。
 * 内部会先把队列里已有的帧全部发完再收应答, 因此会阻塞,
 * 但有 CAR_POS_FLUSH_MS(排队) + CAR_POS_TOTAL_MS(收应答) 两段超时预算,
 * 且超时/坏帧会自动重发查询帧(CAR_POS_QUERY_RETRY 次)。
 * 返回 1 = 读到有效值。 */
uint8_t Car_ReadPositionCount(uint8_t motor_id, int32_t *position);

/* 【清零位置】1~4 号的 S_CPOS 全部清零, 返回 1 表示全部入队成功。 */
uint8_t Car_ResetPositionCounts(void);

/* ---------------- 发送队列 ---------------- */

/* 【主循环每次调用】推进发送队列: 上一帧发完了就发下一帧。
 * 帧与帧之间至少间隔 CAR_FRAME_GAP_MS, 给驱动器留出解析时间。 */
void Car_TxTask(void);

/* 队列里还有没发完的帧(含正在发送的那一帧) */
uint8_t Car_TxBusy(void);

/* 阻塞等待队列排空, 超时返回 0。只在停车确认 / 读位置这种
 * 必须确定"命令已经发完"的场合使用。 */
uint8_t Car_TxFlush(uint32_t timeout_ms);

/* 【诊断】取走并清零"发送异常"计数。
 * 统计的是: 队列满被迫丢帧、DMA 启动失败、以及任何一帧"立即停止"
 * 没能送达(停止帧丢不起, 其余速度命令下一拍会重发, 不计入)。
 * 这个数一直涨说明发送侧有问题, 而不是控制算法。 */
uint32_t Car_TakeTxErrors(void);

#endif /* __FUNCTION_H */
